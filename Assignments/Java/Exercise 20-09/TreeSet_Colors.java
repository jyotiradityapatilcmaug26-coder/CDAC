import java.util.TreeSet;

public class TreeSet_Colors {

    public static void main(String[] args) {

        // Create a TreeSet
        TreeSet<String> colors = new TreeSet<>();

        // Add colors
        colors.add("Red");
        colors.add("Blue");
        colors.add("Green");
        colors.add("Yellow");
        colors.add("Black");

        // Print the TreeSet
        System.out.println("TreeSet:");
        System.out.println(colors);
    }
}